const SVG_NS = 'http://www.w3.org/2000/svg';

function escapeAttr(value) {
  return String(value).replace(/[&<>"]/g, ch => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;' }[ch]));
}

function iconClass(extra = '') {
  return [...new Set(('ico ' + extra).trim().split(/\s+/).filter(Boolean))].join(' ');
}

export function icon(name, extraClass = '') {
  const shapes = ICON_SHAPES[name];
  if (!shapes) return '';
  return `<svg class="${escapeAttr(iconClass(extraClass))}" viewBox="0 0 24 24" aria-hidden="true">${shapes}</svg>`;
}

// Sanitizer-safe placeholder for templates that pass through safeSetHTML:
// svg itself is deliberately outside the HTML allowlist, so hydration swaps
// this span for a DOM-created SVG after sanitization.
export function iconSlot(name, extraClass = '') {
  return `<span data-icon="${escapeAttr(name)}"${extraClass ? ` data-icon-class="${escapeAttr(extraClass)}"` : ''}></span>`;
}

export function createIcon(name, extraClass = '', doc = document) {
  const markup = icon(name, extraClass);
  if (!markup || !doc?.createElementNS) return null;
  const shapes = markup.slice(markup.indexOf('>') + 1, markup.lastIndexOf('</svg>'));
  const svg = doc.createElementNS(SVG_NS, 'svg');
  svg.setAttribute('class', iconClass(extraClass));
  svg.setAttribute('viewBox', '0 0 24 24');
  svg.setAttribute('aria-hidden', 'true');
  for (const shape of shapes.matchAll(/<(path|circle|line|polyline|polygon|rect)\b([^>]*)\/>/g)) {
    const el = doc.createElementNS(SVG_NS, shape[1]);
    for (const attr of shape[2].matchAll(/([\w:.-]+)="([^"]*)"/g)) el.setAttribute(attr[1], attr[2]);
    svg.appendChild(el);
  }
  return svg.childNodes.length ? svg : null;
}

export function hydrateIcons(root = document) {
  if (!root) return 0;
  const slots = [];
  if (root.matches?.('[data-icon]')) slots.push(root);
  if (root.querySelectorAll) slots.push(...root.querySelectorAll('[data-icon]'));
  for (const slot of slots) {
    const svg = createIcon(slot.dataset.icon, slot.dataset.iconClass || '', slot.ownerDocument || document);
    if (svg) slot.replaceWith(svg); else slot.remove();
  }
  return slots.length;
}
